const LABEL = { brief: '브리프', facts: '팩트시트', directions: '방향안', critique: '채점표', verify: '사실 검증', decision: '결정 카드', produce: '시안', review: '시안 크리틱', check: '완료 기준', revise: '수정본', final: '확정', report: '프로젝트 보고', teach: '설명' };

const TYPE_RE = /^\s*[*_`#]*\s*유형\s*[:：]\s*[*_`]*\s*(실행형|사고형|학습형)/m;
// \b 는 한글을 단어 문자로 보지 않으므로, 뒤에 공백·문장부호·끝이 오는지로 판단한다.
const CONFIRM_RE = /^\s*(컨펌|확정|승인|좋아|좋습니다|ok|okay|ㅇㅋ|오케이|진행해|이대로)(?=$|[\s.!,~?ㅎ])/i;
const PASS_RE = /^\s*(패스|pass|맡길게|알아서)/i;
const CANCEL_RE = /^\s*\/(중단|취소|새작업)/;

const block = (title, body) => (body ? `## ${title}\n${String(body).trim()}\n` : '');

function handoff(P, keys) {
  const d = P.docs;
  const parts = [block('사용자 요청', P.request)];
  const map = {
    brief: ['브리프 (플랜)', d.brief],
    answers: ['사용자 답변 (1차 가설·기준)', d.answers],
    facts: ['팩트시트 (서치)', d.facts],
    directions: ['방향안 (에디슨)', d.directions],
    critique: ['채점표 (릭)', d.critique],
    verify: ['사실 검증 (코덱스)', d.verify],
    decision: ['결정 카드 (플랜)', d.decision],
    choice: ['사용자가 고른 방향', d.choice],
    draft: ['시안 보고 (클로드)', d.draft],
    review: ['시안 크리틱', d.review],
    feedback: ['사용자 수정 요청', (d.feedback || []).map((f, i) => `${i + 1}. ${f}`).join('\n')],
  };
  for (const k of keys) if (map[k]) parts.push(block(...map[k]));
  return parts.filter(Boolean).join('\n');
}

