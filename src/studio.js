// 스튜디오 모드: 사고 주권 프로토콜을 따르는 팀 작업 흐름.
//  분류(플랜) → 실행형은 바로 끝까지, 학습형은 설명 + 재진술 요청, 사고형은 아래 단계로.
//  ① 브리프(플랜) ─ 컨펌 A: 내 1차 가설·기준 답변
//  ② 발산(서치·에디슨, 병렬·독립) → ③ 크리틱(릭·코덱스, 병렬) → 결정 카드(플랜) ─ 컨펌 B: 방향 선택
//  ④ 시안(클로드) + 크리틱·검증 ─ 컨펌 C: 컨펌 / 수정 요청 (반복)
//  ⑤ 확정(클로드) → 프로젝트 보고(플랜)
// 각 역할은 대화 전체가 아니라 "지시서 + 필요한 산출물"만 받는다 (MetaGPT식 산출물 전달, 동조 방지, 토큰 절약).

