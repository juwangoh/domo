function parseType(text) {
  return text.match(TYPE_RE)?.[1] || null;
}

function parseTitle(text) {
  return text.match(/^\s*[*_`]*\s*제목\s*[:：]\s*(.+)$/m)?.[1]?.replace(/[*_`]/g, '').trim().slice(0, 30) || null;
}

function parseOptions(text) {
  const found = [...new Set([...text.matchAll(/^\s*#{0,4}\s*\**([A-E])\s*(?:안)?\s*[·.:)\-—]/gm)].map((m) => m[1]))];
  return found.length >= 2 ? found : ['A', 'B', 'C'];
}

function gateMeta(gate, extra = {}) {
  const g = GATES[gate];
  return { kind: 'gate', gate, title: g.title, hint: g.hint, actions: [...(extra.actions || []), ...g.actions] };
}

module.exports = { STAGES, GATES, LABEL, prompts, handoff, parseType, parseTitle, parseOptions, gateMeta, CONFIRM_RE, PASS_RE, CANCEL_RE };
